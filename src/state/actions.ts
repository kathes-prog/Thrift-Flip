/**
 * Shared contract: every committed change to a Project.
 *
 * UI code only dispatches these and renders the resulting state. Each action
 * is handled by exactly one handler file (see reducer.ts for the routing).
 * Every action that changes the project becomes ONE undo step.
 *
 * Changing this file needs review from all three owners (see CODEOWNERS).
 */
import type { DesignMode, FabricPiece, MaterialSource, Project } from '@/model/types';
import type { Point } from '@/model/units';

// ---- sources: handlers/sources.ts (P1)

/** Import a garment (original or additional) with its inventory. Max one additional garment. */
export interface AddGarmentAction {
  type: 'ADD_GARMENT';
  source: MaterialSource;
  pieces: FabricPiece[];
}

/** Add a measured scrap: one rectangular piece, area = width × length. */
export interface AddScrapAction {
  type: 'ADD_SCRAP';
  source: MaterialSource;
  piece: FabricPiece;
}

export interface SelectModeAction {
  type: 'SELECT_MODE';
  mode: DesignMode;
}

// ---- inventory: handlers/inventory.ts (P1)

/** Tray -> canvas. Rejected (state unchanged) when the piece is not an eligible tray piece. */
export interface PlacePieceAction {
  type: 'PLACE_PIECE';
  pieceId: string;
  /** Design coordinates (cm). */
  position: Point;
}

/** Canvas -> stored. */
export interface StorePieceAction {
  type: 'STORE_PIECE';
  pieceId: string;
}

/** Stored -> tray. */
export interface RestorePieceAction {
  type: 'RESTORE_PIECE';
  pieceId: string;
}

/** Any non-discarded status -> discarded. Only Undo brings it back. */
export interface DiscardPieceAction {
  type: 'DISCARD_PIECE';
  pieceId: string;
}

// ---- edits: handlers/edits.ts (P2)

/** Committed once on gesture release, never on every pan frame. */
export interface MovePieceAction {
  type: 'MOVE_PIECE';
  pieceId: string;
  /** New centre in design coordinates (cm). */
  position: Point;
}

export interface RotatePieceAction {
  type: 'ROTATE_PIECE';
  pieceId: string;
  rotationDeg: number;
}

/**
 * Mirror a piece as it looks on screen: 'horizontal' swaps left and right,
 * 'vertical' turns it upside down. Stored as flipped + rotationDeg.
 */
export interface FlipPieceAction {
  type: 'FLIP_PIECE';
  pieceId: string;
  axis: 'horizontal' | 'vertical';
}

export interface RecolorPieceAction {
  type: 'RECOLOR_PIECE';
  pieceId: string;
  color: string;
}

/**
 * Straight cut. Endpoints are in DESIGN coordinates; the handler converts them
 * to the piece's local coordinates. Invalid cuts leave state unchanged.
 * A valid cut replaces the parent with two fragments in one edit.
 */
export interface CutPieceAction {
  type: 'CUT_PIECE';
  pieceId: string;
  from: Point;
  to: Point;
  /** New ids for the two fragments, generated by the caller so the reducer stays pure. */
  fragmentIds: [string, string];
}

/**
 * Sew two overlapping canvas pieces into ONE piece whose outline is both
 * outlines joined. Its areaCm2 is the sum of both (all that fabric is used).
 * Rejected (state unchanged) when the pieces don't overlap.
 */
export interface StitchPiecesAction {
  type: 'STITCH_PIECES';
  pieceIds: [string, string];
  /** Id for the joined piece, generated by the caller so the reducer stays pure. */
  mergedId: string;
}

/**
 * Canvas -> tray: the Studio's Discard button. The piece leaves the design and
 * is available again (P1's DISCARD_PIECE is for fabric thrown away for good).
 */
export interface ReturnPieceAction {
  type: 'RETURN_PIECE';
  pieceId: string;
}

/**
 * Canvas -> tray for EVERY piece on the canvas: the Studio's Reset button.
 * One undo step. Rejected (state unchanged) when the canvas is already empty.
 */
export interface ClearCanvasAction {
  type: 'CLEAR_CANVAS';
}

// ---- history and loading: reducer.ts (shared)

export interface UndoAction {
  type: 'UNDO';
}

/** Re-apply the step that the last UNDO took back. Any new edit clears redo. */
export interface RedoAction {
  type: 'REDO';
}

/** Replace the whole project (open a saved project, load a dev preset). Clears undo history. */
export interface LoadProjectAction {
  type: 'LOAD_PROJECT';
  project: Project;
}

export type SourceAction = AddGarmentAction | AddScrapAction | SelectModeAction;
export type InventoryAction =
  PlacePieceAction | StorePieceAction | RestorePieceAction | DiscardPieceAction;
export type EditAction =
  | MovePieceAction
  | RotatePieceAction
  | FlipPieceAction
  | RecolorPieceAction
  | CutPieceAction
  | StitchPiecesAction
  | ReturnPieceAction
  | ClearCanvasAction;

/** Actions that change the project and are recorded in undo history. */
export type ProjectAction = SourceAction | InventoryAction | EditAction;

export type AppAction = ProjectAction | UndoAction | RedoAction | LoadProjectAction;
